function zhibek_ru_gettext(string $translation, string $text, string $domain): string {
    if (!zhibek_ru_frontend()) {
        return $translation;
    }
    if ($domain === 'woocommerce') {
        return zhibek_ru_dictionary()[$text] ?? $translation;
    }
    if ($domain === 'default') {
        return zhibek_ru_core_dictionary()[$text] ?? $translation;
    }
    return $translation;
}

function zhibek_ru_gettext_context(string $translation, string $text, string $context, string $domain): string {
    return zhibek_ru_gettext($translation, $text, $domain);
}

/** Select the Russian singular, paucal or plural form independently of WP locale. */
function zhibek_ru_plural_index($number): int {
    $number = abs((int) $number);
    $last = $number % 10;
    $last_two = $number % 100;
    if ($last === 1 && $last_two !== 11) {
        return 0;
    }
    if ($last >= 2 && $last <= 4 && ($last_two < 12 || $last_two > 14)) {
        return 1;
    }
    return 2;
}

